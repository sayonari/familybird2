def put16(chrdata, tile_tl, art):
    """16x16アートを tile_tl, tile_tl+1, tile_tl+0x10, tile_tl+0x11 に書く（スプライトテーブル=後半4KB）"""
    for q,(dy,dx) in enumerate([(0,0),(0,8),(8,0),(8,8)]):
        t = tile_tl + [0,1,0x10,0x11][q]
        off = 4096 + t*16
        for y in range(8):
            lo = hi = 0
            for x in range(8):
                c = art[dy+y][dx+x]
                v = int(c) if c in "123" else 0
                if v & 1: lo |= 1 << (7-x)
                if v & 2: hi |= 1 << (7-x)
            chrdata[off+y] = lo
            chrdata[off+8+y] = hi

