def put8(chrdata, tile, art):
    """8x8アートをスプライトテーブルの1タイルに書く"""
    off = 4096 + tile*16
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            c = art[y][x]
            v = int(c) if c in "123" else 0
            if v & 1: lo |= 1 << (7-x)
